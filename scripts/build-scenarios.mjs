import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const sourceDir = path.join(root, "src", "scenario");
const outFile = path.join(root, "src", "data", "scenarios.ts");

const SCENARIO_META = {
  "сценарий_Утечка на линейной части газопровода.txt": {
    id: "pipeline-leak",
    title: "Утечка на линейной части газопровода",
    description:
      "Вы — линейный обходчик. Во время обхода обнаружили характерный запах и шипение у магистрального газопровода DN 1000.",
    difficulty: "Средний",
    categoryTag: "АВАРИИ И ЧС",
    imageSrc: "/icons/trub.jpeg",
  },
};

function parseOptions(lines) {
  const options = [];
  let correctOptionId = "";

  for (const line of lines) {
    const isCorrect = line.startsWith("+");
    const text = (isCorrect ? line.slice(1) : line).trim();
    if (!text) continue;
    const id = `o${options.length}`;
    options.push({ id, text });
    if (isCorrect) correctOptionId = id;
  }

  return { options, correctOptionId };
}

function parseStepBlock(lines) {
  const prompt = lines[0] ?? "";
  const { options, correctOptionId } = parseOptions(lines.slice(1));
  return { prompt, options, correctOptionId };
}

function parseScenarioFile(content) {
  const chunks = content
    .split(/✓\s*Верное решение\s*/i)
    .map((c) =>
      c
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => l.length > 0),
    )
    .filter((c) => c.length > 0);

  const steps = [];

  for (let i = 0; i < chunks.length; i++) {
    const lines = chunks[i];

    if (i === 0) {
      const { prompt, options, correctOptionId } = parseStepBlock(lines);
      steps.push({
        id: `s${steps.length + 1}`,
        prompt,
        options,
        correctOptionId,
        feedback: "",
      });
      continue;
    }

    const questionIdx = lines.findIndex((l) => l.endsWith("?"));
    if (questionIdx === -1) {
      if (steps.length > 0) {
        steps[steps.length - 1].feedback = lines.join(" ");
      }
      continue;
    }

    const feedback = lines.slice(0, questionIdx).join(" ").trim();
    if (steps.length > 0) {
      steps[steps.length - 1].feedback = feedback;
    }

    const { prompt, options, correctOptionId } = parseStepBlock(lines.slice(questionIdx));
    steps.push({
      id: `s${steps.length + 1}`,
      prompt,
      options,
      correctOptionId,
      feedback: "",
    });
  }

  return steps;
}

function escapeString(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const files = fs.readdirSync(sourceDir).filter((f) => f.endsWith(".txt"));
const modules = [];

for (const file of files) {
  const meta = SCENARIO_META[file];
  if (!meta) {
    console.warn(`Skip unknown scenario file: ${file}`);
    continue;
  }
  const raw = fs.readFileSync(path.join(sourceDir, file), "utf8");
  const steps = parseScenarioFile(raw);
  modules.push({ ...meta, steps });
}

const body = modules
  .map(
    (m) => `  {
    id: \`${escapeString(m.id)}\`,
    title: \`${escapeString(m.title)}\`,
    description: \`${escapeString(m.description)}\`,
    difficulty: \`${escapeString(m.difficulty)}\`,
    categoryTag: \`${escapeString(m.categoryTag)}\`,
    imageSrc: \`${escapeString(m.imageSrc)}\`,
    steps: ${JSON.stringify(m.steps, null, 2).replace(/^/gm, "    ").trimStart()},
  }`,
  )
  .join(",\n");

const output = `/* eslint-disable */
// Auto-generated by scripts/build-scenarios.mjs — do not edit by hand

import type { ScenarioModule } from "@/types/scenario";

export const SCENARIO_MODULES: ScenarioModule[] = [
${body}
];
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output, "utf8");
console.log(`Wrote ${modules.length} scenario(s) to ${outFile}`);
