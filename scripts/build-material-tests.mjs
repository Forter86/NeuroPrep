function isMultipleHint(text) {
  const lower = text.toLowerCase();
  return (
    lower.includes("несколько верных") ||
    lower.includes("выберите два") ||
    lower.includes("выберите три") ||
    lower.includes("два правильных") ||
    lower.includes("три правильных")
  );
}

function parseQuestionBlock(raw, index) {
  const lines = raw
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0);

  const multipleMarkerIdx = lines.findIndex((l) => l.startsWith("*"));
  const refIdx = lines.findIndex((l) => l.toLowerCase().startsWith("ссылка на нтд"));

  const bodyEnd = refIdx === -1 ? lines.length : refIdx;
  const body = lines.slice(0, bodyEnd);

  let answerStart = body.findIndex(
    (l, i) =>
      i > 0 &&
      (l.startsWith("+") ||
        (body[i - 1] && !body[i - 1].startsWith("+") && !isMultipleHint(body[i - 1]) && l.length > 0)),
  );

  if (answerStart === -1) {
    answerStart = body.findIndex((l) => l.startsWith("+"));
  }
  if (answerStart === -1) answerStart = body.length;

  const promptLines = body.slice(0, Math.max(1, answerStart)).filter((l) => !l.startsWith("*"));
  const prompt = promptLines.join(" ").trim();

  const answerLines = body.slice(answerStart).filter((l) => !l.startsWith("*"));
  const options = [];
  const correctOptionIds = [];

  for (const line of answerLines) {
    const isCorrect = line.startsWith("+");
    const text = (isCorrect ? line.slice(1) : line).trim();
    if (!text) continue;
    const id = `o${options.length}`;
    options.push({ id, text });
    if (isCorrect) correctOptionIds.push(id);
  }

  const reference =
    refIdx === -1
      ? ""
      : lines
          .slice(refIdx + 1)
          .join(" ")
          .trim();

  const multiple =
    (multipleMarkerIdx !== -1) ||
    isMultipleHint(prompt) ||
    correctOptionIds.length > 1;

  return {
    id: `q${index}`,
    prompt,
    options,
    correctOptionIds,
    multiple,
    reference,
  };
}

function parseFile(filePath) {
  const raw = fs.readFileSync(filePath, "utf8");
  const chunks = raw.split(/Вопрос\s*#\d+\s*/i).filter((c) => c.trim().length > 0);
  return chunks.map((chunk, i) => parseQuestionBlock(chunk, i + 1));
}

function escapeString(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

